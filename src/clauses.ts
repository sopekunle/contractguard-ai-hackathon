const clausesById = new Map(CLAUSES.map((clause) => [clause.id, clause]));

export function getClause(id: string): ClauseEntry | undefined {
  return clausesById.get(id);
}

function searchWords(value: string): string[] {
  return value.toLowerCase().match(/[\p{L}\p{N}]+/gu) ?? [];
}

const clauseSearchWords = CLAUSES.map((clause) => searchWords(
  [clause.name, CLAUSE_CATEGORIES[clause.category], ...clause.keywords].join(' '),
));

export function findClauses(query: string, category: ClauseCategory | 'all' = 'all'): ClauseEntry[] {
  const terms = searchWords(query);
  return CLAUSES.filter((clause, index) =>
    (category === 'all' || clause.category === category) &&
    terms.every((term) => clauseSearchWords[index].some((word) => word.startsWith(term))),
  );
}
